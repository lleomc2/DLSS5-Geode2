#!/usr/bin/env python3
"""Regenerates src/Shaders.hpp from the .glsl files in /shaders (single source of truth)."""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent
items = [("kVert", "vert.glsl"), ("kCommon", "common.glsl"), ("kFragBox", "box.frag.glsl"),
         ("kFragDown", "down.frag.glsl"), ("kFragUp", "up.frag.glsl"), ("kFragEdge", "edge.frag.glsl"),
         ("kFragPack", "pack.frag.glsl"), ("kFragComposite", "composite.frag.glsl"),
         ("kFragCompositeMax", "composite_max.frag.glsl")]
out = ["// AUTO-GENERATED by tools/gen_shaders.py from /shaders/*.glsl - do not edit by hand.",
       "// GLSL ES 1.00 (Geometry Dash on Android renders with an OpenGL ES 2.0 context).",
       "#pragma once", "", "namespace dlss5::shaders {", ""]
for name, fn in items:
    body = (root / "shaders" / fn).read_text()
    assert ')GLSL"' not in body
    out.append(f'static const char* {name} = R"GLSL(\n{body}\n)GLSL";\n')
out.append("} // namespace dlss5::shaders\n")
(root / "src" / "Shaders.hpp").write_text("\n".join(out))
print("wrote src/Shaders.hpp")
